#!/usr/bin/env python3
"""生成分层阅读索引：每份 README 展示相对当前目录的两层条目。

运行 `python3 tools/gen_readme.py` 更新索引，使用 `--check` 仅检查。
文件和目录都占一层；第二层目录只显示链接，其内容在自己的 README 中展示。
"""

import argparse
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional
from urllib.parse import quote


MAX_DEPTH = 2
DOCUMENT_SUFFIXES = {".md", ".pptx"}
GENERATED_MARKER = "<!-- Generated by tools/gen_readme.py; do not edit manually. -->"
LEGACY_LINK_PREFIX = "https://github.com/Uyouii/Reading/blob/master/"
CHINESE_DIGITS = dict(zip("零一二三四五六七八九", range(10)))


def chapter_number(match: re.Match) -> str:
    """把中文章节号转成数字，避免第十章排在第二章之前。"""
    number = total = 0
    for character in match.group(1):
        if character in CHINESE_DIGITS:
            number = CHINESE_DIGITS[character]
        else:
            total += (number or 1) * {"十": 10, "百": 100}[character]
            number = 0
    return f"第{total + number}章"


def sort_key(path: Path) -> tuple:
    name = re.sub(r"第([零一二三四五六七八九十百]+)章", chapter_number, path.name)
    parts = re.split(r"(\d+)", name.casefold())
    return tuple((1, int(part)) if part.isdecimal() else (0, part) for part in parts)


def markdown_text(text: str) -> str:
    escaped = re.sub(r"([\\`*_{}\[\]<>#|])", r"\\\1", text)
    return escaped.replace("\n", " ").replace("\r", " ")


def link(label: str, target: Path, base: Path) -> str:
    url = quote(target.relative_to(base).as_posix(), safe="/")
    return f"[{markdown_text(label)}](./{url})"


def find_readme(directory: Path) -> Path:
    """保留已有文件名大小写，确保链接在 GitHub 上也能打开。"""
    candidates = sorted(
        (entry for entry in directory.iterdir() if entry.name.casefold() == "readme.md"),
        key=lambda entry: (entry.name != "README.md", entry.name),
    )
    return candidates[0] if candidates else directory / "README.md"


def is_generated_readme(path: Path) -> bool:
    """只接管新生成的索引和旧脚本的纯索引，保留手写 README。"""
    if path.is_symlink():
        return False
    if not path.exists():
        return True
    content = path.read_text(encoding="utf-8")
    if content.startswith(GENERATED_MARKER + "\n"):
        return True
    lines = [line for line in content.splitlines() if line.strip()]
    if not lines:
        return True
    if not re.fullmatch(r"#+ .+", lines[0]):
        return False
    legacy_entry = re.compile(
        rf"(?:- \[.*\]\((?:{re.escape(LEGACY_LINK_PREFIX)}|\./)[^\s]+\)"
        rf"|#{{2,}} \*\*\[<font color=#008000>.*</font>\]"
        rf"\({re.escape(LEGACY_LINK_PREFIX)}[^\s]+\)\*\*"
        rf"|#{{2,}} [^\[\]<>]+)"
    )
    return all(legacy_entry.fullmatch(line) for line in lines[1:])


@dataclass
class Directory:
    path: Path
    readme_path: Path
    documents: list[Path] = field(default_factory=list)
    children: list["Directory"] = field(default_factory=list)
    document_count: int = 0
    managed: bool = True


def scan_directory(path: Path) -> Directory:
    """扫描完整目录树；展示深度不影响深层目录自己的索引生成。"""
    readme_path = find_readme(path)
    directory = Directory(path, readme_path, managed=is_generated_readme(readme_path))
    for entry in sorted(path.iterdir(), key=sort_key):
        if entry.is_symlink() or entry.name.startswith((".", "~$", "__pycache__")):
            continue
        if entry.is_dir():
            child = scan_directory(entry)
            if child.document_count or child.children or not child.managed:
                directory.children.append(child)
        elif (
            entry.name.casefold() != "readme.md"
            and entry.suffix.lower() in DOCUMENT_SUFFIXES
        ):
            directory.documents.append(entry)
    directory.document_count = len(directory.documents) + sum(
        child.document_count for child in directory.children
    )
    return directory


def render_entries(directory: Directory, base: Path, depth: int = 1) -> list[str]:
    """目录优先，以缩进表示层次，所有链接均相对当前 README。"""
    lines = []
    indent = "  " * (depth - 1)
    for child in directory.children:
        label = link(child.path.name, child.readme_path, base)
        lines.append(f"{indent}- 📁 **{label}** · {child.document_count} 篇")
        if depth < MAX_DEPTH:
            lines.extend(render_entries(child, base, depth + 1))
    for document in directory.documents:
        icon = "📊" if document.suffix.lower() == ".pptx" else "📄"
        lines.append(f"{indent}- {icon} {link(document.stem, document, base)}")
    return lines


def render_readme(directory: Directory, root: Path) -> str:
    lines = [GENERATED_MARKER, "", f"# {markdown_text(directory.path.name)}", ""]
    if directory.path != root:
        parents = [".."] * len(directory.path.relative_to(root).parts)
        home = quote((Path(*parents) / find_readme(root).name).as_posix())
        parent = quote(f"../{find_readme(directory.path.parent).name}")
        lines.extend([f"[🏠 首页]({home}) · [↩ 返回上级]({parent})", ""])
    lines.extend([
        f"> 共 **{directory.document_count}** 篇文档 · **{len(directory.children)}** 个子目录",
        "> 展示两层条目，点击目录可继续浏览。",
        "",
        "## 阅读目录",
        "",
    ])
    lines.extend(render_entries(directory, directory.path) or ["暂无文档。"])
    return "\n".join(lines) + "\n"


def generate_readmes(
    directory: Directory, root: Path, check: bool = False
) -> tuple[int, int]:
    """生成各层索引，内容未变化时不写盘。返回变化数与保留的手写索引数。"""
    changed = preserved = 0
    for child in directory.children:
        child_changed, child_preserved = generate_readmes(child, root, check)
        changed += child_changed
        preserved += child_preserved
    if not directory.managed:
        print(f"保留手写索引：{directory.readme_path.relative_to(root)}")
        return changed, preserved + 1
    content = render_readme(directory, root)
    previous = (
        directory.readme_path.read_text(encoding="utf-8")
        if directory.readme_path.exists() else None
    )
    if previous != content:
        changed += 1
        if not check:
            directory.readme_path.write_text(content, encoding="utf-8")
    return changed, preserved


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "root", nargs="?", type=Path, default=Path(__file__).resolve().parents[1],
        help="阅读库目录（默认为脚本所在仓库）",
    )
    parser.add_argument(
        "--check", action="store_true", help="仅检查索引是否需要更新，不写入文件"
    )
    args = parser.parse_args(argv)
    root = args.root.resolve()
    if not root.is_dir():
        parser.error(f"目录不存在：{root}")
    changed, preserved = generate_readmes(scan_directory(root), root, args.check)
    action = "待更新" if args.check else "已更新"
    print(f"{action} {changed} 份 README，保留 {preserved} 份手写索引。")
    return int(args.check and changed > 0)


if __name__ == "__main__":
    raise SystemExit(main())
